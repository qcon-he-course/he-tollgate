-- Table definitions for the embedded PostgreSQL test database.
-- Copied from the Liquibase changelogs in tollgate-db (tables, keys and indexes only). The tests do not
-- run Liquibase, so keep this in step when a changelog adds or changes a table. See ADR-0011.

CREATE TABLE structure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(5) NOT NULL,
    name VARCHAR(100) NOT NULL,
    structure_type VARCHAR(12) NOT NULL,
    mass_rating_t INTEGER,
    clearance_m NUMERIC(4,2),
    estuary BOOLEAN DEFAULT false NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(5) NOT NULL,
    entry_junction VARCHAR(5) NOT NULL,
    exit_junction VARCHAR(5) NOT NULL,
    description VARCHAR(200),
    PRIMARY KEY (id)
);

CREATE TABLE route_segment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    route_id BIGINT NOT NULL,
    seq INTEGER NOT NULL,
    structure_id BIGINT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE load_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(40) NOT NULL,
    description VARCHAR(200) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE holiday (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    holiday_date DATE NOT NULL,
    description VARCHAR(100) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE structure_closure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    structure_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(10) NOT NULL,
    recorded_by VARCHAR(50) NOT NULL,
    recorded_at TIMESTAMP NOT NULL,
    ended_by VARCHAR(50),
    ended_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE haulier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(200) NOT NULL,
    contact_name VARCHAR(100),
    contact_email VARCHAR(200) NOT NULL,
    phone VARCHAR(30),
    address_line1 VARCHAR(200),
    town VARCHAR(100),
    postcode VARCHAR(10),
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE operator_licence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    haulier_id BIGINT NOT NULL,
    licence_number VARCHAR(20) NOT NULL,
    valid_from DATE NOT NULL,
    expiry_date DATE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE insurance_policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    haulier_id BIGINT NOT NULL,
    insurer VARCHAR(100) NOT NULL,
    policy_number VARCHAR(40) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    haulier_id BIGINT NOT NULL,
    registration VARCHAR(10) NOT NULL,
    category VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(200),
    enabled BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP NOT NULL,
    is_panel_chair BOOLEAN DEFAULT false NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE user_role (
    user_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    PRIMARY KEY (user_id, role)
);

CREATE TABLE movement_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(20) NOT NULL,
    haulier_id BIGINT NOT NULL,
    vehicle_id BIGINT,
    load_type_id BIGINT,
    load_description VARCHAR(1000),
    gross_mass_kg INTEGER,
    width_m NUMERIC(4,2),
    length_m NUMERIC(5,2),
    height_m NUMERIC(4,2),
    hazardous BOOLEAN DEFAULT false NOT NULL,
    un_number VARCHAR(4),
    route_id BIGINT,
    first_move_date DATE,
    last_move_date DATE,
    status VARCHAR(20) NOT NULL,
    created_by VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    lodged_by VARCHAR(50),
    lodged_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE application_trip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id BIGINT NOT NULL,
    trip_no INTEGER NOT NULL,
    departure_at TIMESTAMP NOT NULL,
    crossing_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    attachment_type VARCHAR(30) NOT NULL,
    size_bytes BIGINT NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    uploaded_by VARCHAR(50) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE question_set (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    load_type_id BIGINT NOT NULL,
    version INTEGER NOT NULL,
    active BOOLEAN DEFAULT true NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    question_set_id BIGINT NOT NULL,
    seq INTEGER NOT NULL,
    question_text VARCHAR(500) NOT NULL,
    mandatory BOOLEAN DEFAULT true NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE case_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id BIGINT NOT NULL,
    seq INTEGER NOT NULL,
    question_text VARCHAR(500) NOT NULL,
    mandatory BOOLEAN NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE case_answer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_question_id BIGINT NOT NULL,
    answer_text VARCHAR(2000),
    answered_at TIMESTAMP,
    review_status VARCHAR(10) NOT NULL,
    review_note VARCHAR(1000),
    reviewed_by VARCHAR(50),
    reviewed_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE permit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(20) NOT NULL,
    application_id BIGINT NOT NULL,
    status VARCHAR(12) NOT NULL,
    issued_by VARCHAR(50) NOT NULL,
    issued_at TIMESTAMP NOT NULL,
    status_reason VARCHAR(500),
    status_changed_at TIMESTAMP,
    suspended_by_closure_id BIGINT,
    version INTEGER DEFAULT 1 NOT NULL,
    window_start DATE,
    window_end DATE,
    case_id BIGINT,
    PRIMARY KEY (id)
);

CREATE TABLE permit_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    permit_id BIGINT NOT NULL,
    content BYTEA NOT NULL,
    content_type VARCHAR(50) NOT NULL,
    generated_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE permit_ref_counter (
    ref_year INTEGER NOT NULL,
    last_value INTEGER NOT NULL,
    PRIMARY KEY (ref_year)
);

CREATE TABLE audit_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(20) NOT NULL,
    entity_type VARCHAR(20) NOT NULL,
    old_state VARCHAR(30),
    new_state VARCHAR(30) NOT NULL,
    actor VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    reason VARCHAR(500),
    PRIMARY KEY (id)
);

CREATE TABLE notification_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(20),
    recipient VARCHAR(200) NOT NULL,
    template VARCHAR(50) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    status VARCHAR(10) NOT NULL,
    error_message VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE case_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reference VARCHAR(20) NOT NULL,
    application_id BIGINT NOT NULL,
    haulier_id BIGINT NOT NULL,
    state VARCHAR(30) NOT NULL,
    outcome VARCHAR(30),
    track VARCHAR(20),
    escalated_track VARCHAR(20),
    risk_score INTEGER,
    warnings VARCHAR(200),
    assigned_officer VARCHAR(50),
    assigned_engineer VARCHAR(50),
    officer_comments VARCHAR(2000),
    lodged_at TIMESTAMP NOT NULL,
    decided_at TIMESTAMP,
    closed_reason VARCHAR(500),
    updated_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE assessment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    score INTEGER NOT NULL,
    score_track VARCHAR(20) NOT NULL,
    final_track VARCHAR(20) NOT NULL,
    assessed_at TIMESTAMP NOT NULL,
    superseded BOOLEAN DEFAULT false NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE assessment_factor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    assessment_id BIGINT NOT NULL,
    factor VARCHAR(20) NOT NULL,
    points INTEGER NOT NULL,
    detail VARCHAR(200),
    PRIMARY KEY (id)
);

CREATE TABLE trigger_hit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    assessment_id BIGINT NOT NULL,
    trigger_code VARCHAR(30) NOT NULL,
    min_track VARCHAR(20) NOT NULL,
    detail VARCHAR(200),
    PRIMARY KEY (id)
);

CREATE TABLE decision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    outcome VARCHAR(30) NOT NULL,
    reason VARCHAR(2000),
    decided_by VARCHAR(50) NOT NULL,
    decided_at TIMESTAMP NOT NULL,
    panel BOOLEAN DEFAULT false NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE permit_condition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    permit_id BIGINT,
    condition_type VARCHAR(20) NOT NULL,
    detail VARCHAR(500),
    escort_vehicles INTEGER,
    structure_code VARCHAR(5),
    source VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE engineer_assessment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    engineer VARCHAR(50) NOT NULL,
    recommendation VARCHAR(30) NOT NULL,
    notes VARCHAR(4000),
    proposed_conditions VARCHAR(1000),
    recorded_at TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE query_round (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    round_no INTEGER NOT NULL,
    issued_by VARCHAR(50) NOT NULL,
    issued_on DATE NOT NULL,
    deadline DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    answered_at TIMESTAMP,
    reminder_sent BOOLEAN DEFAULT false NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE query_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    query_round_id BIGINT NOT NULL,
    seq INTEGER NOT NULL,
    question_text VARCHAR(1000) NOT NULL,
    answer_text VARCHAR(2000),
    PRIMARY KEY (id)
);

CREATE TABLE panel_sitting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sitting_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE panel_listing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    panel_sitting_id BIGINT NOT NULL,
    case_id BIGINT NOT NULL,
    listed_at TIMESTAMP NOT NULL,
    result VARCHAR(20),
    PRIMARY KEY (id)
);

CREATE TABLE amendment_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    permit_id BIGINT NOT NULL,
    new_first_move_date DATE NOT NULL,
    new_last_move_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    warnings VARCHAR(200),
    requested_by VARCHAR(50) NOT NULL,
    requested_at TIMESTAMP NOT NULL,
    decided_by VARCHAR(50),
    decided_at TIMESTAMP,
    reason VARCHAR(500),
    PRIMARY KEY (id)
);

CREATE TABLE incident (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    haulier_id BIGINT NOT NULL,
    incident_date DATE NOT NULL,
    description VARCHAR(500) NOT NULL,
    recorded_by VARCHAR(50),
    recorded_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE api_key (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    haulier_id BIGINT NOT NULL,
    api_key VARCHAR(40) NOT NULL,
    label VARCHAR(100),
    active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP NOT NULL,
    last_used_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE sla_clock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    started_on DATE NOT NULL,
    stopped_on DATE,
    target_days INTEGER NOT NULL,
    elapsed_days INTEGER DEFAULT 0 NOT NULL,
    paused_days INTEGER DEFAULT 0 NOT NULL,
    status VARCHAR(10) NOT NULL,
    calculated_on DATE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE sla_pause (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    case_id BIGINT NOT NULL,
    cause VARCHAR(30) NOT NULL,
    started_on DATE NOT NULL,
    ended_on DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE permit_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    permit_id BIGINT NOT NULL,
    permit_reference VARCHAR(20) NOT NULL,
    version INTEGER NOT NULL,
    old_status VARCHAR(12),
    new_status VARCHAR(12) NOT NULL,
    changed_by VARCHAR(63) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id)
);

